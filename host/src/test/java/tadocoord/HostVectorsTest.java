package tadocoord;

import static org.junit.jupiter.api.Assertions.assertEquals;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;
import java.util.OptionalInt;
import org.junit.jupiter.api.Test;
import tadocoord.coap.CoapMessage;
import tadocoord.lowpan.Datagram;
import tadocoord.tado.ConfigDocuments;
import tadocoord.tado.TadoResources;

/**
 * golden/host_vectors.txt: what the Java host builds, for the gateway's C port to match byte for
 * byte. The file must match the code; regenerate it with {@code -Dgolden.write=true}.
 */
class HostVectorsTest {
    private static final Path FILE = Path.of("../golden/host_vectors.txt");

    private final Eui coordinator = Golden.eui("in.coord_eui");
    private final Eui device = Golden.eui("in.joiner_eui");
    private final List<String> lines = new ArrayList<>();

    @Test
    void hostVectorsMatchTheCode() throws Exception {
        lines.add("# Generated by host HostVectorsTest from the Java host. Do not edit;");
        lines.add("# regenerate with ./mvnw test -Dtest=HostVectorsTest -Dgolden.write=true.");
        lines.add("# Coordinator in.coord_eui, device in.joiner_eui, home 4242.");

        put("doc.device_config", ConfigDocuments.deviceConfig(4242, List.of(
                new ConfigDocuments.ZoneRole(ConfigDocuments.ROLE_OWNER, 11),
                new ConfigDocuments.ZoneRole(ConfigDocuments.ROLE_MEMBER, 12))));
        byte[] zone = ConfigDocuments.zoneWithOwner(device);
        put("doc.zone_with_owner", zone);
        put("doc.zone_state", ConfigDocuments.zoneState(1800));
        put("doc.zone_state_overlay", ConfigDocuments.zoneState(1800, OptionalInt.of(2100)));
        put("doc.zone_uri", ConfigDocuments.zoneUri(device).getBytes(StandardCharsets.US_ASCII));
        put("doc.etag_zone", ConfigDocuments.etag(zone));
        put("doc.session_id", tadocoord.join.JoinSessionAccess.sessionId(device));

        // GET h/4242/z/11/config in turn: block 0 asked at 128, block 1 asked at 64, block 1
        // asked at 128 as the sensor does (NUM counts our 64-byte blocks), the last block, and
        // block 0 with the ETag held.
        int[][] blocks = {{0x0201, 0x03}, {0x0202, 0x12}, {0x0203, 0x13}, {0x0204, 0x32}};
        for (int i = 0; i < blocks.length; i++) {
            CoapMessage get = zoneGet(blocks[i][0], blocks[i][1], null);
            put("req.block" + i, request(get));
            put("res.block" + i, ConfigDocuments.blockAnswer(get, zone, from(get), coordinator, device));
        }
        CoapMessage held = zoneGet(0x0205, 0x03, ConfigDocuments.etag(zone));
        put("req.block_held", request(held));
        put("res.block_held", ConfigDocuments.blockAnswer(held, zone, from(held), coordinator, device));

        CoapMessage report = new CoapMessage(CoapMessage.Type.CON, CoapMessage.code(0, 3), 0xa339, new byte[] {7},
                List.of(CoapMessage.path("z"), CoapMessage.path("p")), new byte[] {0x40, 0x60, 0x02, 0x07, 0x08});
        put("req.report", request(report));
        put("res.changed", TadoResources.changedAnswer(report, from(report), coordinator, device));

        CoapMessage separate = new CoapMessage(CoapMessage.Type.CON, CoapMessage.code(2, 4), 0x7777, new byte[0],
                List.of(), new byte[0]);
        put("req.separate", request(separate));
        put("res.empty_ack", TadoResources.emptyAck(separate, from(separate), coordinator, device));

        put("res.zone_state_write", TadoResources.zoneStateWrite(11, ConfigDocuments.zoneState(1800), 0x1234,
                coordinator, device));

        String text = String.join("\n", lines) + "\n";
        if (Boolean.getBoolean("golden.write")) {
            Files.writeString(FILE, text);
        }
        assertEquals(text, Files.readString(FILE), "golden/host_vectors.txt is stale: regenerate it");
    }

    private CoapMessage zoneGet(int mid, int block2, byte[] etag) {
        List<CoapMessage.Option> options = new ArrayList<>();
        if (etag != null) {
            options.add(new CoapMessage.Option(4, etag));
        }
        for (String s : "h/4242/z/11/config".split("/")) {
            options.add(CoapMessage.path(s));
        }
        options.add(new CoapMessage.Option(23, new byte[] {(byte) block2}));
        return new CoapMessage(CoapMessage.Type.CON, CoapMessage.code(0, 1), mid, new byte[] {0x3c}, options,
                new byte[0]);
    }

    private byte[] request(CoapMessage m) {
        return Datagram.udp(device, coordinator, Datagram.COAP_PORT, Datagram.COAP_PORT, m.encode());
    }

    private Datagram from(CoapMessage m) {
        return Datagram.parse(request(m), device, Optional.of(coordinator));
    }

    private void put(String name, byte[] value) {
        lines.add(name + " " + Hex.of(value));
    }
}
