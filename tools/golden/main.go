// Command golden writes the shared test vectors (golden/vectors.txt) that the
// firmware and host tests check against. Every frame comes from freedo's
// exported builders with fixed inputs, so the vectors are reproducible:
//
//	cd tools/golden && go run . > ../../golden/vectors.txt
package main

import (
	"encoding/hex"
	"fmt"
	"net/netip"
	"strconv"
	"time"

	"freedo/tado"
)

var (
	pairingKey  = []byte("tado pairing key")
	networkKey  = mustHex("0f1e2d3c4b5a69788796a5b4c3d2e1f0")
	coordEUI    = mustHex("09a1cefa07c51b00") // wire order, ends in the tado suffix
	joinerEUI   = mustHex("0bb1cefa07c51b00")
	pairSession = mustHex("0102030405060708")
	sessionID   = mustHex("a1a2a3a4a5a6a7a8")
)

func main() {
	fmt.Println("# Generated by tools/golden from freedo builders. Do not edit.")
	fmt.Println("# Format: name hex. Inputs are listed as their own entries.")
	put("in.network_key", networkKey)
	put("in.coord_eui", coordEUI)
	put("in.joiner_eui", joinerEUI)
	put("in.pair_session", pairSession)
	put("in.session_id", sessionID)

	// Enhanced Beacon Request (freedo test vector) and the beacon answer.
	put("beacon_request.frame", mustHex("0be87bffffffff0bb1cefa07c51b0004581463f90147ed74caf1bd"))
	eb := must(tado.BuildEnhancedBeacon(pairingKey, 0x59, joinerEUI, coordEUI, 13537))
	put("enh_beacon.frame", eb) // seq 0x59, counter 13537

	// Wake-up frames and Enhanced ACK.
	put("wakeup.bcast_3125", tado.BuildWakeUp(0x10, []byte{0xff, 0xff}, 3125))
	put("wakeup.unicast_248", tado.BuildWakeUp(0x11, []byte{0xb1, 0x0b}, 248))
	burst := tado.BuildRouterAdvertWakeUpBurst(0x12)
	put("wakeup.ra_burst_first", burst[0])
	put("wakeup.ra_burst_last", burst[len(burst)-1])
	fmt.Printf("wakeup.ra_burst_count %02x\n", len(burst))
	put("enh_ack.frame", tado.BuildEnhAck(0x22, joinerEUI, coordEUI, 0x0123)) // phase 0x0123

	// d/pair CoAP datagram (BuildPairCoAP with a fixed option-2048 value).
	pair := must(tado.BuildCoAP(tado.CoAPReq{
		Type: "CON", Code: "0.02", MID: 0x1234, Token: []byte{},
		Path:    []string{"d", "pair"},
		Options: []tado.CoAPOption{{Num: 12, Val: []byte{42}}, {Num: 2048, Val: pairSession}},
		Payload: append([]byte{0x12, 0x10}, networkKey...),
		SrcEUI:  coordEUI, DstEUI: joinerEUI, SrcPort: 5683, DstPort: 5683,
	}))
	put("pair.coap", pair)                               // MID 0x1234
	pairPT := tado.WrapAppPayload(pair, 0x00000100, nil) // counter 0x100
	pf := must(tado.BuildData(pairingKey, 0x30, joinerEUI, coordEUI[:5], pairPT))
	put("pair.frame", pf.Bytes()) // seq 0x30, pairing key

	// The valve's 2.04 answer, sealed under the network key.
	ans := must(tado.BuildCoAPAck("2.04", 0x1234, []byte{}, nil, joinerEUI, coordEUI, 5683, 5683))
	put("pair_answer.coap", ans)
	af := must(tado.BuildData(networkKey, 0x05, coordEUI, joinerEUI[:5], tado.WrapAppPayload(ans, 0x00000007, nil)))
	put("pair_answer.frame", af.Bytes()) // seq 0x05, counter 7, network key

	// auth/token and time answers (piggybacked ACKs from the coordinator).
	body := must(tado.BuildAuthTokenBody(sessionID))
	put("auth_token.coap", must(tado.BuildCoAPAck("2.05", 0x4321, []byte{0xaa, 0xbb}, body, coordEUI, joinerEUI, 5683, 5683)))
	now := time.Unix(1786619383, 0)
	put("time.coap", must(tado.BuildTimeCoAP(now, 0x5555, []byte{0xcc}, coordEUI, joinerEUI, 5683, 5683)))

	// Router Advertisement and its two broadcast copies.
	ra := must(tado.BuildRouterAdvert(coordEUI, tado.BridgeRouterAdvert(coordEUI, netip.IPv4Unspecified(), netip.IPv4Unspecified())))
	put("ra.packet", ra)
	raPT := tado.WrapBroadcastPayload(ra, 0x0000) // counter high 0
	put("ra.frame_network_pending", must(tado.BuildBroadcastPending(networkKey, 0x40, coordEUI, 0x0200, 0x04, raPT)))
	put("ra.frame_pairing", must(tado.BuildBroadcast(pairingKey, 0x41, coordEUI, 0x0201, 0x04, raPT)))

	// Zone state writes (PUT z/s?id=11) for home and away, and the boost: the
	// tests compare their payload, the z/s block.
	sp := func(c tado.SetpointCoAP) []byte {
		c.ID, c.MID, c.Token, c.SrcEUI, c.DstEUI = 11, 0x0606, []byte{0x06}, coordEUI, joinerEUI
		return must(tado.BuildSetpointCoAP(c))
	}
	put("zone.away_warm", sp(tado.SetpointCoAP{Home: false, SchedC: 20, AwayC: 15, NewOverlay: true}))
	put("zone.away_off", sp(tado.SetpointCoAP{Home: false, SchedC: 20, NewOverlay: true}))
	put("zone.home_again", sp(tado.SetpointCoAP{Home: true, SchedC: 20, NewOverlay: true}))
	put("zone.away_manual", sp(tado.SetpointCoAP{Home: false, SchedC: 20, AwayC: 15, Overlay: 2, Setpoint: 21}))
	boost := func(c tado.BoostCoAP) []byte {
		c.ID, c.MID, c.Token, c.SrcEUI, c.DstEUI = 11, 0x0707, []byte{0x07}, coordEUI, joinerEUI
		return must(tado.BuildBoostCoAP(c))
	}
	put("zone.boost_on", boost(tado.BoostCoAP{Enabled: true, Home: true, SchedC: 20, NewOverlay: true}))
	put("zone.boost_cancel", boost(tado.BoostCoAP{Enabled: false, Home: true, SchedC: 20, NewOverlay: true}))
	put("zone.boost_away", boost(tado.BoostCoAP{Enabled: true, Home: false, SchedC: 20, NewOverlay: true}))

	thermostatDocuments()
}

// thermostatInstall is freedo's own test installation (tado/zone_read_test.go):
// a wall thermostat with hot water (zone 0) as the heat source of circuit 1,
// and a valve in heating zone 4 on that circuit.
const thermostatInstall = `
version: 1
home_id: 7654321
network_key: "000102030405060708090a0b0c0d0e0f"
coordinator:
  eui: "1000000000c51b00"
  serial: IB0000000001
devices:
  - {kind: thermostat, eui: "2000000000c51b00", serial: RU0000000001, label: hall}
  - {kind: valve, eui: "3000000000c51b00", serial: VA0000000001, label: study}
zones:
  - {number: 0, name: water, kind: hotwater, members: [RU0000000001]}
  - {number: 4, name: study, kind: heating, circuit: 1, members: [VA0000000001], reporter: VA0000000001}
circuits:
  - {id: 1, name: house, heat_source: RU0000000001}
`

// thermostatDocuments puts the documents freedo's emulator serves in that
// installation (the d/config of the thermostat before and after it reported
// its interface module id, the valve's, and the zone documents), as their
// bodies, assembled over Block2.
func thermostatDocuments() {
	in := must(tado.Parse([]byte(thermostatInstall)))
	offset := 120 // tag 02b2: fixed, so the host's zone and date stay out of the bytes
	in.Options.UTCOffsetMin = &offset
	ru := must(in.Resolve("RU0000000001")).WireEUI()
	va := must(in.Resolve("VA0000000001")).WireEUI()
	e := tado.NewEmu(in.EmuConfig(), nil)
	home := strconv.FormatUint(uint64(in.HomeID), 10)
	mid := uint16(0x7000)

	request := func(dev []byte, code string, path []string, options []tado.CoAPOption, payload []byte) *tado.CoAPMessage {
		mid++
		pkt := must(tado.BuildCoAP(tado.CoAPReq{
			Type: "CON", Code: code, MID: mid, Token: []byte{0x21}, Path: path, Options: options, Payload: payload,
			SrcEUI: dev, DstEUI: in.CoordinatorEUI(), SrcPort: 5683, DstPort: 4005,
		}))
		f := must(tado.BuildData(in.NetworkKey(), 0x41, in.CoordinatorEUI(), dev[:5], tado.WrapAppPayload(pkt, 700, nil)))
		for _, a := range e.OnFrame(f.Bytes()) {
			if a.Kind != tado.ActData {
				continue
			}
			df, err := tado.ParseData(in.NetworkKey(), a.Bytes)
			if err != nil {
				continue
			}
			if app := tado.ParseApp(df.Plaintext); app != nil && app.CoAP != nil && app.CoAP.MID == mid {
				return app.CoAP
			}
		}
		panic(fmt.Sprintf("no answer to %v", path))
	}
	// A document, block by block (64-byte blocks, as the devices take them).
	document := func(dev []byte, path ...string) []byte {
		var body []byte
		for block := 0; ; block++ {
			m := request(dev, "0.01", path, []tado.CoAPOption{{Num: 23, Val: []byte{byte(block<<4 | 2)}}}, nil)
			if m.Code != "2.05" {
				panic(fmt.Sprintf("%v: %s", path, m.Code))
			}
			body = append(body, m.Payload...)
			if o, ok := m.Option(23); !ok || o.Val[len(o.Val)-1]&0x08 == 0 {
				return body
			}
		}
	}

	put("in.thermostat_eui", ru)
	put("in.thermostat_valve_eui", va)
	put("in.thermostat_home_id", []byte{byte(in.HomeID >> 24), byte(in.HomeID >> 16), byte(in.HomeID >> 8), byte(in.HomeID)})
	put("thermostat.config_no_module", document(ru, "d", "RU0000000001", "config"))
	// The thermostat reports its interface module id (tag 015d) in hvac/codes:
	// 80, as on a Vaillant ecoTEC plus on eBUS (freedo issue #37).
	request(ru, "0.03", []string{"h", home, "hvac", "codes"}, nil, []byte{0x01, 0x5d, 0x02, 0x00, 0x50})
	put("thermostat.config_module_80", document(ru, "d", "RU0000000001", "config"))
	put("thermostat.valve_config", document(va, "d", "VA0000000001", "config"))
	put("thermostat.zone_heating", document(va, "h", home, "z", "4", "config"))
	put("thermostat.zone_hotwater", document(ru, "h", home, "z", "0", "config"))
}

func put(name string, b []byte) { fmt.Printf("%s %s\n", name, hex.EncodeToString(b)) }

func must[T any](v T, err error) T {
	if err != nil {
		panic(err)
	}
	return v
}

func mustHex(s string) []byte {
	b, err := hex.DecodeString(s)
	if err != nil {
		panic(err)
	}
	return b
}
